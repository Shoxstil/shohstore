import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { seedProducts } from "../server/seed.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/main.tsx"],
  bundle: true,
  write: false,
  outdir: "standalone",
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  jsx: "automatic",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  loader: { ".woff2": "dataurl" },
  legalComments: "inline",
});
const js = result.outputFiles.find((f) => f.path.endsWith(".js"))?.text;
const css = result.outputFiles.find((f) => f.path.endsWith(".css"))?.text;
if (!js || !css)
  throw Error("Standalone build did not produce JavaScript and CSS.");
const favicon = await readFile(
  new URL("../public/favicon.svg", import.meta.url),
  "utf8",
);
const json = (value) => JSON.stringify(value).replace(/</g, "\\u003c");
const config = `window.__SHOHSTORE_STANDALONE__=true;window.__SHOHSTORE_CATALOG__=${json(seedProducts)};`;
const html = `<!doctype html>
<!-- Generated by npm run build:standalone. Edit src/, not this generated file. -->
<html lang="ru"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><meta name="theme-color" content="#f8f7f4"><meta name="description" content="Shohstore — компьютеры и комплектующие. Автономный просмотр каталога и конструктора ПК."><title>Shohstore — каталог и конструктор ПК</title><link rel="icon" href="data:image/svg+xml,${encodeURIComponent(favicon)}"><style>${css.replace(/<\/style/gi, "<\\/style")}</style></head>
<body><div id="root"><p style="font-family:Arial,sans-serif;padding:40px">Загружаем Shohstore… Если страница не открылась, включите JavaScript в браузере. Для полного магазина запустите START-SHOHSTORE.bat (Windows) или START-SHOHSTORE.command (macOS).</p></div><noscript>Для просмотра Shohstore включите JavaScript в браузере.</noscript><script>${config}${js.replace(/<\/script/gi, "<\\/script")}</script></body></html>
`;
await writeFile(new URL("../index.html", import.meta.url), html);
console.log(
  `Standalone index.html: ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB; scripts, fonts, catalog and images embedded. No server or CDN required for browsing.`,
);
