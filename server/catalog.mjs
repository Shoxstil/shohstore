function build(id, name, price, ids, extra = {}) {
  const parts = ids.map((id) => catalog.find((p) => p.id === id));
  if (parts.some((p) => !p)) throw Error("Unknown build component: " + name);
  const find = (c) =>
    parts.find(
      (p) =>
        p.category === c ||
        (c === "motherboard" && p.category.startsWith("mb-")),
    );
  const specs = {
    Processor: find("cpu").name,
    Graphics: find("gpu").name,
    Motherboard: find("motherboard").name,
    Memory: find("ram").name,
    Storage: find("ssd").name,
    "Power supply": find("psu").name,
    Cooling: parts.find((p) => ["cooler", "liquid"].includes(p.category)).name,
    Case: find("case").name,
    Socket: find("cpu").socket,
    "Memory standard": find("ram").specs.Type,
    "CPU cores": find("cpu").specs.Cores,
    "CPU threads": find("cpu").specs.Threads,
    "Video memory": find("gpu").specs.Memory,
    Capacity: "1 TB",
    "Operating system": "Not installed",
    Peripherals: "Not included",
  };
  return add(
    id,
    name,
    "build",
    price,
    specs,
    {
      ru: `${term(name, "ru")}: ${term(specs.Processor, "ru")} и ${term(specs.Graphics, "ru")}, ${term(specs.Memory, "ru")}. Накопитель — ${term(specs.Storage, "ru")}, плата — ${term(specs.Motherboard, "ru")}. Установлены ${term(specs["Power supply"], "ru")}, ${term(specs.Cooling, "ru")} и корпус ${term(specs.Case, "ru")}. ОС, монитор и периферия в цену не входят. Все конкретные компоненты перечислены в характеристиках.`,
      en: `${name} pairs ${specs.Processor} with ${specs.Graphics} and ${specs.Memory}. Storage: ${specs.Storage}; motherboard: ${specs.Motherboard}. PSU: ${specs["Power supply"]}; cooler: ${specs.Cooling}; case: ${specs.Case}. Operating system, monitor and peripherals are not included. All component models are listed below.`,
      uz: `${term(name, "uz")}: ${term(specs.Processor, "uz")}, ${term(specs.Graphics, "uz")} va ${term(specs.Memory, "uz")}. SSD ${term(specs.Storage, "uz")}, plata ${term(specs.Motherboard, "uz")}. ${term(specs["Power supply"], "uz")} bloki, ${term(specs.Cooling, "uz")} sovitishi va ${term(specs.Case, "uz")} korpusi. OS, monitor va periferiya narxga kirmaydi. Aniq qismlar xususiyatlarda berilgan.`,
    },
    { brand: "SHOHSTORE", ...extra },
  );
}
