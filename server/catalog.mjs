      ru: `${term(name, "ru")}: ${term(cores, "ru")} ядер и ${term(threads, "ru")} потоков на архитектуре ${term(arch, "ru")}, сокет ${term(socket, "ru")}. Базовая частота — ${term(base, "ru")}, максимальная — ${term(boost, "ru")}; кэш L3 — ${term(l3, "ru")}, номинальный TDP — ${term(tdp, "ru")}. Поддерживаемая память: ${term(memory, "ru")}. Встроенная графика: ${term(graphics, "ru")}.`,
